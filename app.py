class HybridRow(dict):
    def __init__(self, columns, values):
        super().__init__(zip(columns, values))
        self._values = tuple(values)

    def __getitem__(self, key):
        if isinstance(key, int):
            return self._values[key]
        return super().__getitem__(key)

    def __iter__(self):
        return super().__iter__()


def hybrid_row_factory(cursor):
    return lambda values: HybridRow(
        [column.name for column in cursor.description],
        values
    )


def get_db():
    database_url = os.environ.get("DATABASE_URL")

    if database_url:
        import psycopg

        return psycopg.connect(
            database_url,
            row_factory=hybrid_row_factory
        )

    sqlite_conn = sqlite3.connect(
        DATABASE,
        timeout=30
    )
    sqlite_conn.row_factory = sqlite3.Row

    class SQLiteCompatConnection:
        def __init__(self, connection):
            self._connection = connection

        def execute(self, sql, params=()):
            return self._connection.execute(
                sql.replace("%s", "?"),
                params
            )

        def executemany(self, sql, params):
            return self._connection.executemany(
                sql.replace("%s", "?"),
                params
            )

        def executescript(self, script):
            return self._connection.executescript(script)

        def commit(self):
            return self._connection.commit()

        def rollback(self):
            return self._connection.rollback()

        def close(self):
            return self._connection.close()

        def __enter__(self):
            self._connection.__enter__()
            return self

        def __exit__(self, exc_type, exc_value, traceback):
            return self._connection.__exit__(
                exc_type,
                exc_value,
                traceback
            )

    return SQLiteCompatConnection(sqlite_conn)

def allowed_file(filename, allowed_extensions):
    return (
        "." in filename
        and filename.rsplit(".", 1)[1].lower() in allowed_extensions
    )


def ensure_column(conn, column_name, column_definition):

    if os.environ.get("DATABASE_URL"):
        columns = conn.execute(
            """
            SELECT column_name AS name
            FROM information_schema.columns
            WHERE table_name = 'students'
            """
        ).fetchall()
    else:
        columns = conn.execute(
            "PRAGMA table_info(students)"
        ).fetchall()

    existing_columns = [
        column["name"] for column in columns
    ]

    if column_name not in existing_columns:

        conn.execute(
            f"ALTER TABLE students ADD COLUMN "
            f"{column_name} {column_definition}"
        )


