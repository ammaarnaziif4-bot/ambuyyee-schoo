@app.route("/")
def home():
    conn = get_db()

    # Active academic year
    active_year = conn.execute(
        """
        SELECT id, year_name
        FROM academic_years
        WHERE is_active = 1
        LIMIT 1
        """
    ).fetchone()

    if active_year:
        year_id = active_year["id"]
        year_name = active_year["year_name"]
    else:
        year_id = None
        year_name = "Current Academic Year"

    # Home page statistics
    # Total Students = academic-year registration target.
    # Registered Students = completed registrations only.
    # Approved Students = teacher-approved registrations.
    # Pending students are intentionally excluded.
    total_students = 0
    registered_students = 0
    approved_students = 0

    if year_id:
        target_row = conn.execute(
            """
            SELECT total_students
            FROM registration_targets
            WHERE academic_year_id = %s
            """,
            (year_id,)
        ).fetchone()

        if target_row:
            total_students = target_row["total_students"] or 0

        registered_students = conn.execute(
            """
            SELECT COUNT(*)
            FROM students
            WHERE academic_year_id = %s
            AND registration_status IN ('passed', 'failed')
            """,
            (year_id,)
        ).fetchone()[0]

        approved_students = conn.execute(
            """
            SELECT COUNT(*)
            FROM students
            WHERE academic_year_id = %s
            AND registration_status = 'passed'
            """,
            (year_id,)
        ).fetchone()[0]

        total_students = registered_students

    # Grade statistics
    grade_stats = []

    for grade in [9, 10, 11, 12]:
        registered = 0
        approved = 0

        if year_id:
            registered = conn.execute(
                """
                SELECT COUNT(*)
                FROM students
                WHERE academic_year_id = %s
                AND registration_status IN ('passed', 'failed')
                AND class_name LIKE %s
                """,
                (year_id, f"{grade}%")
            ).fetchone()[0]

            approved = conn.execute(
                """
                SELECT COUNT(*)
                FROM students
                WHERE academic_year_id = %s
                AND registration_status = 'passed'
                AND class_name LIKE %s
                """,
                (year_id, f"{grade}%")
            ).fetchone()[0]

        percentage = (
            round((approved / registered) * 100, 1)
            if registered > 0 else 0
        )

        grade_stats.append({
            "grade": grade,
            "registered": registered,
            "approved": approved,
            "percentage": percentage
        })

    # Class / section statistics
    class_stats = []

    if year_id:
        rows = conn.execute(
            """
            SELECT
                class_name,
                COUNT(*) AS registered,
                SUM(
                    CASE
                        WHEN registration_status = 'passed'
                        THEN 1
                        ELSE 0
                    END
                ) AS approved
            FROM students
            WHERE academic_year_id = %s
            AND registration_status IN ('passed', 'failed')
            AND class_name IS NOT NULL
            AND TRIM(class_name) != ''
            GROUP BY class_name
            ORDER BY class_name ASC
            """,
            (year_id,)
        ).fetchall()

        for row in rows:
            registered = row["registered"] or 0
            approved = row["approved"] or 0

            percentage = (
                round((approved / registered) * 100, 1)
                if registered > 0 else 0
            )

            class_stats.append({
                "class_name": row["class_name"],
                "registered": registered,
                "approved": approved,
                "percentage": percentage
            })

    conn.close()

    return render_template(
        "index.html",
        active_year_name=year_name,
        total_students=total_students,
        registered_students=registered_students,
        approved_students=approved_students,
        grade_stats=grade_stats,
        class_stats=class_stats
    )


