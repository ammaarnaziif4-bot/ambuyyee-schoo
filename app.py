@app.route("/director/restore-data", methods=["GET", "POST"])
def director_restore_data():
    if not session.get("director_logged_in"):
        flash("Please login as a director first.")
        return redirect(url_for("director_login"))

    import shutil
    import json
    from datetime import datetime

    os.makedirs("backups", exist_ok=True)

    if request.method == "POST":
        action = request.form.get("action", "")

        # PostgreSQL backup
        if action == "backup" and os.environ.get("DATABASE_URL"):
            timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
            filename = f"school_backup_{timestamp}.json"
            backup_path = os.path.join("backups", filename)

            conn = get_db()

            tables = conn.execute(
                """
                SELECT table_name
                FROM information_schema.tables
                WHERE table_schema = 'public'
                  AND table_type = 'BASE TABLE'
                ORDER BY table_name
                """
            ).fetchall()

            backup_data = {}

            for table in tables:
                table_name = table["table_name"]

                columns = conn.execute(
                    """
                    SELECT column_name
                    FROM information_schema.columns
                    WHERE table_schema = 'public'
                      AND table_name = %s
                    ORDER BY ordinal_position
                    """,
                    (table_name,)
                ).fetchall()

                column_names = [c["column_name"] for c in columns]

                rows = conn.execute(
                    f'SELECT * FROM "{table_name}"'
                ).fetchall()

                backup_data[table_name] = {
                    "columns": column_names,
                    "rows": [dict(row) for row in rows]
                }

            conn.close()

            with open(backup_path, "w", encoding="utf-8") as f:
                json.dump(
                    backup_data,
                    f,
                    ensure_ascii=False,
                    indent=2,
                    default=str
                )

            conn = get_db()
            conn.execute(
                """
                INSERT INTO system_backups (filename)
                VALUES (%s)
                """,
                (filename,)
            )
            conn.commit()
            conn.close()

            flash("Database backup created successfully.")

        # SQLite backup
        elif action == "backup":
            timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
            filename = f"school_backup_{timestamp}.db"
            backup_path = os.path.join("backups", filename)

            source = sqlite3.connect(DATABASE)
            destination = sqlite3.connect(backup_path)

            source.backup(destination)

            destination.close()
            source.close()

            conn = get_db()
            conn.execute(
                """
                INSERT INTO system_backups (filename)
                VALUES (%s)
                """,
                (filename,)
            )
            conn.commit()
            conn.close()

            flash("Database backup created successfully.")

        # PostgreSQL restore
        elif action == "restore" and os.environ.get("DATABASE_URL"):
            filename = request.form.get("filename", "").strip()
            backup_path = os.path.join("backups", filename)

            if not filename or not filename.endswith(".json"):
                flash("Invalid PostgreSQL backup file.")
                return redirect(url_for("director_restore_data"))

            if not os.path.isfile(backup_path):
                flash("Backup file not found.")
                return redirect(url_for("director_restore_data"))

            with open(backup_path, "r", encoding="utf-8") as f:
                backup_data = json.load(f)

            conn = get_db()

            try:
                tables = conn.execute(
                    """
                    SELECT table_name
                    FROM information_schema.tables
                    WHERE table_schema = 'public'
                      AND table_type = 'BASE TABLE'
                    ORDER BY table_name
                    """
                ).fetchall()

                table_names = [t["table_name"] for t in tables]

                # Restore in dependency-safe order:
                # disable foreign-key checks through deferred constraints
                conn.execute("SET CONSTRAINTS ALL DEFERRED")

                for table_name in reversed(table_names):
                    if table_name in backup_data:
                        conn.execute(f'DELETE FROM "{table_name}"')

                for table_name, table_data in backup_data.items():
                    if table_name not in table_names:
                        continue

                    columns = table_data.get("columns", [])
                    rows = table_data.get("rows", [])

                    if not columns or not rows:
                        continue

                    quoted_columns = ", ".join(
                        f'"{column}"' for column in columns
                    )
                    placeholders = ", ".join(
                        ["%s"] * len(columns)
                    )

                    query = (
                        f'INSERT INTO "{table_name}" '
                        f'({quoted_columns}) '
                        f'VALUES ({placeholders})'
                    )

                    for row in rows:
                        values = [row.get(column) for column in columns]
                        conn.execute(query, values)

                conn.commit()
                flash("Database restored successfully.")

            except Exception as e:
                conn.rollback()
                flash(f"Restore failed: {e}")

            finally:
                conn.close()

        # SQLite restore
        elif action == "restore":
            filename = request.form.get("filename", "").strip()

            if filename:
                backup_path = os.path.join("backups", filename)

                if os.path.isfile(backup_path):
                    source = sqlite3.connect(backup_path)
                    destination = sqlite3.connect(DATABASE)

                    source.backup(destination)

                    destination.close()
                    source.close()

                    flash("Database restored successfully.")
                else:
                    flash("Backup file not found.")

        return redirect(url_for("director_restore_data"))

    conn = get_db()

    backups = conn.execute(
        """
        SELECT *
        FROM system_backups
        ORDER BY id DESC
        """
    ).fetchall()

    conn.close()

    return render_template(
        "director_restore.html",
        backups=backups
    )


